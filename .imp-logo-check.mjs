import { chromium } from 'playwright';
import fs from 'node:fs';
const token = fs.readFileSync('/tmp/imp-app-token.txt', 'utf8').trim();
const b = await chromium.launch();
const page = await b.newPage({ viewport: { width: 1440, height: 900 } });
await page.goto('http://localhost:3001/landing', { waitUntil: 'load', timeout: 120000 });
await page.waitForLoadState('networkidle', { timeout: 60000 }).catch(() => {});
await page.waitForTimeout(2000);
await page.screenshot({ path: '/tmp/logo-landing-top.png', clip: { x: 0, y: 0, width: 1440, height: 110 } });
const links = await page.evaluate(() => Array.from(document.querySelectorAll('link[rel*="icon"]')).map(l => `${l.rel} ${l.href} ${l.getAttribute('sizes') ?? ''} ${l.type ?? ''}`));
console.log(links.join('\n'));
await page.goto('http://localhost:3001/login', { waitUntil: 'load', timeout: 120000 });
await page.evaluate((t) => window.localStorage.setItem('botbook_token', t), token);
await page.goto('http://localhost:3001/', { waitUntil: 'load', timeout: 120000 });
await page.waitForLoadState('networkidle', { timeout: 60000 }).catch(() => {});
await page.waitForTimeout(1500);
await page.screenshot({ path: '/tmp/logo-app-top.png', clip: { x: 0, y: 0, width: 1440, height: 100 } });
await b.close();
